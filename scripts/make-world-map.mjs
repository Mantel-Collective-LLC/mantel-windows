import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { geoContains, geoEqualEarth } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "shared", "ui", "src", "ui", "map", "world-dots.ts");

const WIDTH = 1000;
const STEP = 4;
const NORTH = 83;
const SOUTH = -56;

const topology = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topology, topology.objects.land);

const projection = geoEqualEarth().fitWidth(WIDTH, { type: "Sphere" });
const top = projection([0, NORTH])[1];
const bottom = projection([0, SOUTH])[1];
const [tx, ty] = projection.translate();
projection.translate([tx, ty - top]);
const height = Math.ceil(bottom - top);

const columns = Math.floor(WIDTH / STEP);
const rows = Math.floor(height / STEP);
const lines = [];
let dots = 0;
for (let row = 0; row < rows; row += 1) {
  const runs = [];
  let start = -1;
  for (let column = 0; column <= columns; column += 1) {
    let inside = false;
    if (column < columns) {
      const point = projection.invert([column * STEP + STEP / 2, row * STEP + STEP / 2]);
      const back = point && projection(point);
      inside = Boolean(
        point &&
          back &&
          Math.abs(back[0] - (column * STEP + STEP / 2)) < 0.01 &&
          Math.abs(back[1] - (row * STEP + STEP / 2)) < 0.01 &&
          geoContains(land, point),
      );
    }
    if (inside && start < 0) start = column;
    if (!inside && start >= 0) {
      runs.push(`${start.toString(36)}.${(column - start).toString(36)}`);
      dots += column - start;
      start = -1;
    }
  }
  lines.push(runs.join(","));
}

const source = `// Generated by scripts/make-world-map.mjs, do not edit. Data: world-atlas 2.0.2 (ISC) / Natural Earth (public domain).
// Equal Earth projection, ${dots} land dots on a ${STEP}-unit grid.

/** Size of the map in SVG units and the projection that places a coordinate on it (see projection.ts). */
export const WORLD = {
  width: ${WIDTH},
  height: ${height},
  step: ${STEP},
  scale: ${projection.scale()},
  translateX: ${projection.translate()[0]},
  translateY: ${projection.translate()[1]},
} as const;

/** One line per grid row (top to bottom): comma-separated runs "start.length" of land columns, base 36. */
export const WORLD_ROWS = ${JSON.stringify(lines.join("\n"))};
`;
writeFileSync(out, source);
console.log(`${out}: ${dots} dots, ${rows} rows, ${Buffer.byteLength(source)} bytes`);
